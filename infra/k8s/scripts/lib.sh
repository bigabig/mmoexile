# kubectl and helm against one of our clusters (never the current
# context): kc eu get pods, hc central list
kc() { local cluster=$1; shift; kubectl --context "$(context "$cluster")" "$@"; }
hc() { local cluster=$1; shift; helm --kube-context "$(context "$cluster")" "$@"; }

step() { printf '\n\033[1m▸ %s\033[0m\n' "$*"; }
fail() { printf '\033[31m✘ %s\033[0m\n' "$*" >&2; exit 1; }

# `linkerd check` for one cluster: control plane, proxies and extensions;
# prints what failed and returns non-zero. Two of the multicluster checks
# are skipped: they connect from this host to the linked clusters' API
# servers by the names in the Links (the nodes' names on kind's network),
# which only resolve inside the clusters. Shared trust holds by
# construction (every cluster's issuer is signed by our CA), and
# cluster-up.sh waits for the links' gateways instead.
linkerd_check() {
  local result
  # Its own exit code counts the skipped checks too
  result=$(linkerd --context "$(context "$1")" check -o json --wait 2m 2>/dev/null) || true
  node -e '
    const skipped = ["remote cluster access credentials are valid", "clusters share trust anchors"];
    let input = "";
    process.stdin.on("data", (d) => (input += d)).on("end", () => {
      const failed = [];
      // One JSON document for the core checks, one per extension
      for (const doc of input.trim().split(/\n(?=\{)/)) {
        for (const category of JSON.parse(doc).categories) {
          for (const check of category.checks) {
            if (check.result === "error" && !skipped.includes(check.description)) {
              failed.push(`${category.categoryName}: ${check.description}: ${check.error ?? ""}`);
            }
          }
        }
      }
      console.log(failed.length ? failed.join("\n") : "linkerd check: all passed");
      process.exit(failed.length ? 1 : 0);
    });' <<<"$result"
}

# The clusters whose exported Services a cluster mirrors (Linkerd
# multicluster links): central sees the regions' entry points, each region
# sees central's services
linked_clusters() {
  case "$1" in
    central) echo "${REGIONS[@]}" ;;
    *) echo central ;;
  esac
}

cluster_exists() { kind get clusters 2>/dev/null | grep -qx "$(cluster_name "$1")"; }
require_clusters() {
  for cluster in "${CLUSTERS[@]}"; do
    cluster_exists "$cluster" || fail "No cluster $(cluster_name "$cluster") (pnpm cluster:up)"
  done
}

# Runs "<function> <cluster>" for several clusters at once, each line of
# output prefixed with the cluster; fails if any of them failed.
# for_clusters <function> <cluster>...
for_clusters() {
  local fn=$1 pids=() cluster failed=0
  shift
  for cluster in "$@"; do
    ( set -o pipefail; "$fn" "$cluster" 2>&1 | sed -u "s/^/[$cluster] /" ) &
    pids+=($!)
  done
  for pid in "${pids[@]}"; do wait "$pid" || failed=1; done
  (( failed == 0 )) || fail "$fn failed (see above)"
}

image() { echo "mmoexile/$1:$IMAGE_TAG"; }

# Builds one image from the repository: an app, "migrate" or "client"
build_image() {
  local name=$1
  case "$name" in
    client) docker build -q -f "$ROOT/infra/docker/client.Dockerfile" -t "$(image client)" "$ROOT" ;;
    migrate) docker build -q -f "$ROOT/infra/docker/node.Dockerfile" --target migrate -t "$(image migrate)" "$ROOT" ;;
    *) docker build -q -f "$ROOT/infra/docker/node.Dockerfile" --build-arg "APP=$name" -t "$(image "$name")" "$ROOT" ;;
  esac >/dev/null
}

# Loads images into a cluster: load_images <cluster> <image>...
# (kind skips images the node already has in the same version)
load_images() {
  local cluster=$1
  shift
  kind load docker-image --name "$(cluster_name "$cluster")" "$@" 2>&1 | grep -vE "not yet present|already present" || true
}
# The images a cluster runs (built from the repository)
cluster_images() {
  case "$1" in
    central) for name in migrate account-api social orchestrator directory client; do image "$name"; done ;;
    *) image instance-server ;;
  esac
}
