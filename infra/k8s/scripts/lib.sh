# A database container's address on kind's network (PgBouncer: Postgres')
db_address() {
  docker inspect -f "{{(index .NetworkSettings.Networks \"$DB_NETWORK\").IPAddress}}" "$(db_container "$1")"
}

# Points a cluster's database Services (overlays/kind-common/databases.yaml,
# overlays/central/databases.yaml) at the containers' current addresses:
# one EndpointSlice per Service. apply_db_endpoints <cluster>
apply_db_endpoints() {
  local cluster=$1 ip_postgres ip_redis
  ip_postgres=$(db_address postgres)
  ip_redis=$(db_address redis)
  {
    # PgBouncer and the Postgres/PgBouncer exporters share Postgres' network
    # namespace (and address), the Redis exporter Redis'
    endpoint_slice pgbouncer "$ip_postgres" postgres 6432
    endpoint_slice redis "$ip_redis" redis 6380
    if [[ "$cluster" == central ]]; then
      endpoint_slice postgres "$ip_postgres" postgres 5432
      endpoint_slice postgres-exporter "$ip_postgres" metrics 9187
      endpoint_slice pgbouncer-exporter "$ip_postgres" metrics 9127
      endpoint_slice redis-exporter "$ip_redis" metrics 9121
    fi
  } | kc "$cluster" apply -f - >/dev/null
  echo "$cluster: pgbouncer → $ip_postgres:6432, redis → $ip_redis:6380$([[ "$cluster" == central ]] && echo ", postgres → $ip_postgres:5432, exporters")"
}
endpoint_slice() {
  cat <<END
apiVersion: discovery.k8s.io/v1
kind: EndpointSlice
metadata:
  name: $1-external
  namespace: $NAMESPACE
  labels:
    kubernetes.io/service-name: $1
    endpointslice.kubernetes.io/managed-by: cluster-db.mmoexile.dev
    app.kubernetes.io/part-of: mmoexile
addressType: IPv4
ports: [{ name: $3, port: $4, protocol: TCP }]
endpoints: [{ addresses: ["$2"], conditions: { ready: true } }]
---
END
}

# Removes kind's Docker network once neither a kind cluster nor another
# container (databases, cloud-provider-kind) uses it
remove_unused_network() {
  docker network inspect "$DB_NETWORK" >/dev/null 2>&1 || return 0
  [[ -z "$(kind get clusters 2>/dev/null)" ]] || return 0
  [[ "$(docker network inspect -f '{{len .Containers}}' "$DB_NETWORK")" == 0 ]] || return 0
  docker network rm "$DB_NETWORK" >/dev/null && echo "Removed Docker network $DB_NETWORK"
}

# True if PgBouncer (as mmoexile_app) and Redis (as mmoexile) answer over
# verified TLS. Passwords go through the environment, not the arguments.
db_ready() {
  PGPASSWORD=$(secret postgres-app-password) docker exec -e PGPASSWORD "$(db_container postgres)" \
    psql "host=localhost port=6432 dbname=mmoexile user=mmoexile_app sslmode=verify-full sslrootcert=/tls/ca.crt" \
    -tAc "select 1" >/dev/null 2>&1 &&
    REDISCLI_AUTH=$(secret redis-password) docker exec -e REDISCLI_AUTH "$(db_container redis)" \
      redis-cli --tls --cacert /tls/ca.crt -p 6380 --user mmoexile ping 2>/dev/null | grep -q PONG
}

